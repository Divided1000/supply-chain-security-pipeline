"""Control 4 — Build provenance / attestation (SLSA-style).

A signature (control 3) proves "this artifact is authentic and unchanged." Provenance
answers the next question: **where did it come from and how was it built?** It's a signed
statement *about* the artifact — who built it, from which source commit, with what inputs,
when. This is what would have exposed SolarWinds: the backdoor was injected in the build,
so a trustworthy record of "what went into the build" is the control that catches a
compromised build system.

The industry model is **SLSA** (Supply-chain Levels for Software Artifacts) carried in an
**in-toto attestation**: a statement with
  * a **subject** — the artifact it's about, pinned by digest (so the attestation can't
    be re-pointed at a different artifact);
  * a **predicate** — the build facts (builder identity, source repo + commit, the
    materials/inputs, timestamps).

The whole statement is then signed (control 3's machinery), so you get an *authenticated*
record of provenance. SLSA defines levels (L1-L4) by how tamper-resistant that record is;
the key jump is that higher levels require the provenance to be generated by the build
platform itself, not the author, so a developer can't forge it.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import datetime, timezone

from .signing import PrivateKey, PublicKey, Signature, sign_content, verify_signature

PREDICATE_TYPE = "https://slsa.dev/provenance/v1"
STATEMENT_TYPE = "https://in-toto.io/Statement/v1"


@dataclass
class Provenance:
    artifact_name: str
    artifact_digest: str          # binds this statement to one exact artifact
    builder_id: str               # who/what performed the build (trusted identity)
    source_repo: str
    source_commit: str
    build_type: str
    materials: list[dict] = field(default_factory=list)  # inputs, e.g. SBOM digest
    built_at: str = ""

    def to_statement(self) -> dict:
        """Render as an in-toto Statement wrapping an SLSA provenance predicate."""
        return {
            "_type": STATEMENT_TYPE,
            "subject": [
                {"name": self.artifact_name, "digest": {"sha256": self.artifact_digest}}
            ],
            "predicateType": PREDICATE_TYPE,
            "predicate": {
                "buildDefinition": {
                    "buildType": self.build_type,
                    "resolvedDependencies": self.materials,
                    "externalParameters": {
                        "source": self.source_repo,
                        "commit": self.source_commit,
                    },
                },
                "runDetails": {
                    "builder": {"id": self.builder_id},
                    "metadata": {"startedOn": self.built_at},
                },
            },
        }

    def to_json(self) -> str:
        return json.dumps(self.to_statement(), indent=2, sort_keys=True)


def build_provenance(
    artifact_name: str,
    artifact_digest: str,
    sbom_digest: str,
    builder_id: str = "scs-pipeline@local",
    source_repo: str = "github.com/example/sample-app",
    source_commit: str = "0000000000000000000000000000000000000000",
    build_type: str = "https://scs/build/manifest@v1",
    built_at: str | None = None,
) -> Provenance:
    return Provenance(
        artifact_name=artifact_name,
        artifact_digest=artifact_digest,
        builder_id=builder_id,
        source_repo=source_repo,
        source_commit=source_commit,
        build_type=build_type,
        materials=[{"uri": "sbom", "digest": {"sha256": sbom_digest}}],
        built_at=built_at or datetime.now(timezone.utc).isoformat(),
    )


@dataclass
class SignedProvenance:
    statement: str          # the provenance JSON (bytes that were signed)
    signature: Signature

    def to_dict(self) -> dict:
        return {"statement": self.statement, "signature": self.signature.to_dict()}

    @staticmethod
    def from_dict(d: dict) -> "SignedProvenance":
        return SignedProvenance(d["statement"], Signature.from_dict(d["signature"]))


def sign_provenance(prov: Provenance, priv: PrivateKey, pub: PublicKey) -> SignedProvenance:
    statement = prov.to_json()
    sig = sign_content("provenance", statement.encode(), priv, pub)
    return SignedProvenance(statement=statement, signature=sig)


def verify_provenance(signed: SignedProvenance) -> bool:
    """Signature is valid and the signed bytes match the recorded statement."""
    return verify_signature(signed.statement.encode(), signed.signature)


def provenance_subject_digest(signed: SignedProvenance) -> str:
    """Extract the artifact digest this provenance is bound to."""
    stmt = json.loads(signed.statement)
    return stmt["subject"][0]["digest"]["sha256"]


def main() -> None:
    import argparse
    from .sbom import generate_sbom
    from .signing import digest_artifact, digest_bytes, generate_keypair

    parser = argparse.ArgumentParser(description="Generate + sign build provenance.")
    parser.add_argument("--artifact", default="sample-app")
    args = parser.parse_args()

    art_digest = digest_artifact(args.artifact)
    sbom_digest = digest_bytes(generate_sbom(args.artifact).to_json().encode())
    pub, priv = generate_keypair()

    prov = build_provenance(args.artifact, art_digest, sbom_digest)
    signed = sign_provenance(prov, priv, pub)

    print(signed.statement)
    print(f"\nprovenance signature valid : {verify_provenance(signed)}")
    print(f"bound to artifact digest   : {provenance_subject_digest(signed)[:16]}...")


if __name__ == "__main__":
    main()
